#!/usr/bin/env python3
"""Create a compact, portable example from a successfully checked demo run."""
import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'lib'))
from publish_result_assets import render_report, table


def export(run, output):
    check = json.loads((run / 'demo_check.json').read_text())
    if check['status'] != 'passed':
        raise ValueError('Source demo has not passed its checks')
    if output.exists():
        raise ValueError('Choose a new snapshot directory')
    source = run / 'cross'
    finals = table(source / 'results/final_loci.tsv')
    if len(finals) != 1 or finals[0]['query_id'] != 'demo_A.t1':
        raise ValueError('Source is not the bundled positive demo')
    output.mkdir(parents=True)
    for rel in ['final_loci.tsv', 'final_loci.bed', 'final_loci.gff3',
                'final_queries.txt', 'loci.tsv', 'queries.tsv', 'summary.json']:
        target = output / 'results' / rel
        target.parent.mkdir(exist_ok=True)
        shutil.copy2(source / 'results' / rel, target)
    (output / 'qc').mkdir()
    shutil.copy2(source / 'qc/stage_counts.tsv', output / 'qc/stage_counts.tsv')
    summary = json.loads((source / 'results/summary.json').read_text())
    qc = json.loads((source / 'qc/input_qc.json').read_text())
    (output / 'qc/input_qc.json').write_text(json.dumps(dict(
        status=qc['status'], input_records=summary['input_total_records'],
        accepted_queries=summary['input_queries'], excluded_records=summary['input_excluded_records'],
        scope='Compact synthetic installation snapshot'), indent=2) + '\n')
    original_manifest = json.loads((source / 'metadata/run_manifest.json').read_text())
    manifest = dict(species='synthetic_demo', comparison_mode='cross', workflow='standard',
                    analysis_version=original_manifest['analysis_version'],
                    snapshot_only=True, origin='Bundled synthetic installation demo',
                    viewer_scope='Final candidate table; selectable all/final GeneWise overview',
                    report_version=(Path(__file__).resolve().parents[2] / 'VERSION').read_text().strip())
    (output / 'metadata').mkdir()
    (output / 'metadata/run_manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    raw = (source / 'work/genewise/pseudogene-genewise.txt').read_text()
    positive = [block for block in raw.split('//') if 'Query protein:       demo_A.t1\n' in block]
    if len(positive) != 1:
        raise ValueError('Expected one positive GeneWise block')
    (output / 'genewise_alignments.txt').write_text(raw)
    (output / 'genewise_candidate.txt').write_text(positive[0].strip() + '\n//\n')
    (output / 'report.html').write_text(render_report(output, manifest, summary, finals))
    (output / 'README.md').write_text('''# Example detected candidate

This compact snapshot was generated by the bundled synthetic installation
demo. Open [report.html](report.html) for the statistics, final candidate's
alignment, highlighted stop and frameshift, and downloadable result tables.
The searchable candidate table shows 20 rows per page. Click a candidate ID
to expand its alignment below the row. Seven offline overview charts and
five statistics are above the table; choose all completed GeneWise alignments
or final candidate alignments using the scope selector.

The candidate is **demo_A.t1** on **cross_disrupted_A**: one verified premature
stop, one frameshift, 100% query coverage and approximately 99.33% amino-acid
identity. The intact demo_B.t1 control is excluded from the final set.

These are synthetic computational candidates, not experimentally verified
pseudogenes. This is a viewing snapshot, not a reusable pipeline cache. Run
`bash examples/demo/run_demo.sh` from the source checkout to generate complete
outputs independently. The report, candidate search and alignments work
offline, without external libraries.

Coordinates in TSV/BED are 0-based, half-open; GFF3 is 1-based, inclusive.
The raw [GeneWise candidate output](genewise_candidate.txt) is also included.
''')
    provenance = dict(analysis_version=manifest['analysis_version'],
                      source='Existing checked execution of the bundled synthetic demo',
                      candidate_query='demo_A.t1', dataset_seed=20261013,
                      files={str(p.relative_to(output)): hashlib.sha256(p.read_bytes()).hexdigest()
                             for p in sorted(output.rglob('*')) if p.is_file()})
    (output / 'snapshot.json').write_text(json.dumps(provenance, indent=2) + '\n')
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--run', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    try:
        path = export(args.run, args.output)
    except (ValueError, OSError, KeyError) as error:
        raise SystemExit('ERROR: ' + str(error))
    print(f'Exported portable positive demo snapshot: {path}')


if __name__ == '__main__':
    main()
